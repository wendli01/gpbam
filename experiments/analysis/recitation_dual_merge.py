"""Assemble the *GPBam laws* recitation battery on the dual extractor's provisions.

``build_gp_laws_dual.py`` re-derives the 100 most-cited provisions with the
``§``/``Art.`` extractor in ``analysis/refs.py``: 73 of the published 100 survive,
27 are replaced (24 of them GG articles the refex gazetteer could not see).  The
73 survivors already have answers in the published sweep; the 27 newcomers were
generated by ``recitation_dual_delta.py``.

This joins the two into one battery per model and reports what the swap does to
each model's recitation score, so the change to Table 1 is auditable rather than
a number that simply moves.

Run from ``experiments/``::

    python analysis/recitation_dual_merge.py
"""
import sys
from glob import glob
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))

AR = ROOT / 'experiments/zubaers_result/article_recitation'
DUAL = AR / 'dual'
DATASET = 'GPBam Laws'
COLS = ['model', 'dataset', 'query', 'target', 'answer', 'score']


def published():
    frames = [pd.read_csv(AR / 'article_recitation.csv', usecols=COLS)]
    for path in sorted(glob(str(AR / 'recitation_*.csv'))):
        frames.append(pd.read_csv(path, usecols=lambda c: c in set(COLS)))
    d = pd.concat(frames, ignore_index=True)
    return d[d.dataset == DATASET].copy()


def delta():
    files = sorted(glob(str(DUAL / 'delta_*.csv')))
    if not files:
        raise SystemExit('no delta_*.csv -- run analysis/recitation_dual_delta.py first')
    d = pd.concat([pd.read_csv(f, usecols=lambda c: c in set(COLS)) for f in files],
                  ignore_index=True)
    return d


def main():
    new = pd.read_csv(ROOT / 'experiments/data/gp_laws_dual.csv', dtype={'article': str})
    old = pd.read_csv(ROOT / 'experiments/data/gp_laws.csv', dtype={'article': str})
    key = lambda b, a: (str(b).strip().lower() + ' ' + str(a).strip().lower())
    dual_keys = {key(b, a) for b, a in zip(new.law_book, new.article)}
    old_keys = {key(b, a) for b, a in zip(old.law_book, old.article)}

    pub, dlt = published(), delta()
    for d in (pub, dlt):
        d['key'] = d['query'].str.strip().str.lower()

    kept = pub[pub.key.isin(dual_keys & old_keys)]
    added = dlt[dlt.key.isin(dual_keys - old_keys)]
    battery = pd.concat([kept.assign(source='published'),
                         added.assign(source='new')], ignore_index=True)
    battery[['book', 'section']] = battery['query'].str.split(' ', n=1, expand=True)

    out = DUAL / 'recitation_dual_gpbam_laws.csv'
    battery.drop(columns='key').to_csv(out, index=False)
    print(f'{len(battery)} rows, {battery.model.nunique()} models '
          f'({battery.key.nunique()} distinct provisions: '
          f'{kept.key.nunique()} kept + {added.key.nunique()} new) -> {out.name}')

    # per-model: published 100 vs dual 100, on scored answers only
    def mean(d):
        return 100 * d.score.mean(), d.score.notna().sum()

    rows = []
    for m, g in battery.groupby('model'):
        dual_mu, n_dual = mean(g)
        pub_g = pub[(pub.model == m) & pub.key.isin(old_keys)]
        pub_mu, n_pub = mean(pub_g)
        kept_mu, _ = mean(g[g.source == 'published'])
        new_mu, n_new = mean(g[g.source == 'new'])
        rows.append(dict(model=m, published=round(pub_mu, 2), n_pub=n_pub,
                         dual=round(dual_mu, 2), n_dual=n_dual,
                         kept73=round(kept_mu, 2), new27=round(new_mu, 2), n_new=n_new,
                         delta=round(dual_mu - pub_mu, 2)))
    t = pd.DataFrame(rows).sort_values('dual', ascending=False)
    t['rank_pub'] = t.published.rank(ascending=False).astype(int)
    t['rank_dual'] = t.dual.rank(ascending=False).astype(int)
    t['move'] = t.rank_pub - t.rank_dual
    t.to_csv(DUAL / 'recitation_dual_by_model.csv', index=False)
    print(t.to_string(index=False))
    print(f'\nmean shift {t.delta.mean():+.2f}, '
          f'max riser {t.move.max():+d}, max faller {t.move.min():+d}')
    missing = t[t.n_dual < 100]
    if len(missing):
        print('\nincomplete batteries:')
        print(missing[['model', 'n_dual', 'n_new']].to_string(index=False))


if __name__ == '__main__':
    main()
